"""Episode folders: the files an episode is made from, and the checks run on them.

Each episode lives in episodes/NNN-<slug>/:

    brief.toml       guest, host, format and themes (written by `deadman new`)
    research/        one notes file per chapter (NN-<chapter-id>.md), so researchers can work in parallel
    transcript.md    the script itself: the source of truth, edited by hand or by agents
    packaging.toml   titles, thumbnail text, description, cold open and clips
    review.md        the fact-checker's findings
    script.md, youtube-description.txt, episode.json   generated by `deadman render`

Transcript format:

    # Episode title
    > One-line hook

    ## Chapter title

    RAM: A host line, which may wrap
    over several lines until a blank line.

    SMITH: A guest line ending with the passages it relies on. [won-0004, rae-0003]
"""

from __future__ import annotations

import json
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path

from .figures import Figure, load_figure
from .longform import Clip, Packaging, load_format
from .render import slugify
from .script import WORDS_PER_MINUTE, Chapter, Episode, Issue, Segment, mechanical_checks
from .sources import load_passages

EPISODES_DIR = Path(__file__).resolve().parent.parent / "episodes"
LONG_UNCITED_WORDS = 40

_CITATIONS = re.compile(r"\s*\[((?:[a-z]+-\d{4})(?:\s*,\s*[a-z]+-\d{4})*)\]\s*$")
_SPEAKER = re.compile(r"^([A-Z][A-Z .'-]*?):\s+(.*)$", re.S)


class EpisodeFileError(ValueError):
    pass


@dataclass
class Brief:
    number: int
    figure: str
    host: str
    format: str = "longform"
    themes: str = ""


def load_brief(folder: Path) -> Brief:
    path = folder / "brief.toml"
    if not path.exists():
        raise EpisodeFileError(f"{folder} has no brief.toml")
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return Brief(**{k: data[k] for k in ("number", "figure", "host", "format", "themes") if k in data})


def write_brief(brief: Brief) -> str:
    return "\n".join([
        f"number = {brief.number}",
        f"figure = {json.dumps(brief.figure)}",
        f"host = {json.dumps(brief.host)}",
        f"format = {json.dumps(brief.format)}",
        f"themes = {json.dumps(brief.themes)}",
    ]) + "\n"


# --- transcript.md ---

def parse_transcript(text: str, host_label: str, guest_label: str) -> tuple[str, str, list[Chapter]]:
    title, hook, chapters = "", "", []
    speakers = {host_label.upper(): "HOST", guest_label.upper(): "GUEST"}
    # Headings and the hook are always blocks of their own, even without blank lines around them.
    text = re.sub(r"^([#>].*)$", r"\n\1\n", text, flags=re.M)
    for n, block in enumerate(re.split(r"\n\s*\n", text.strip()), 1):
        block = " ".join(line.strip() for line in block.strip().splitlines())
        if not block:
            continue
        if block.startswith("## "):
            chapters.append(Chapter(title=block[3:].strip(), segments=[]))
        elif block.startswith("# "):
            title = block[2:].strip()
        elif block.startswith(">"):
            hook = block.lstrip("> ").strip()
        elif m := _SPEAKER.match(block):
            label, body = m.group(1).strip(), m.group(2)
            if label not in speakers:
                raise EpisodeFileError(f"Block {n}: unknown speaker {label!r} (expected {' or '.join(speakers)})")
            citations = []
            if c := _CITATIONS.search(body):
                citations = [x.strip() for x in c.group(1).split(",")]
                body = body[: c.start()]
            if not chapters:
                chapters.append(Chapter(title=title or "Episode", segments=[]))
            chapters[-1].segments.append(Segment(speaker=speakers[label], text=body.strip(), citations=citations))
        else:
            raise EpisodeFileError(f"Block {n} is not a heading or a 'SPEAKER: text' line: {block[:60]!r}")
    if not title:
        raise EpisodeFileError("transcript.md needs a '# Title' line")
    return title, hook, chapters


def write_transcript(ep: Episode, host_name: str) -> str:
    labels = {"HOST": host_name.upper(), "GUEST": ep.figure.speaker_label}
    out = [f"# {ep.title}", "", f"> {ep.hook}", ""]
    for ch in ep.chapters:
        out += [f"## {ch.title}", ""]
        for seg in ch.segments:
            refs = f" [{', '.join(seg.citations)}]" if seg.citations else ""
            out += [f"{labels[seg.speaker]}: {seg.text}{refs}", ""]
    return "\n".join(out)


# --- packaging.toml ---
# Clips and the cold open point at transcript lines by a short quoted snippet, not a segment
# number, so editing the transcript does not silently move them.

def _anchor(segments: list[Segment], index: int) -> str:
    words = segments[index].text.split()
    for n in range(6, len(words) + 1):
        snippet = " ".join(words[:n])
        if sum(snippet in s.text for s in segments) == 1:
            return snippet
    return segments[index].text


def _resolve(segments: list[Segment], snippet: str, what: str) -> int:
    hits = [i for i, s in enumerate(segments) if snippet in s.text]
    if len(hits) != 1:
        problem = "matches no line" if not hits else f"matches {len(hits)} lines"
        raise EpisodeFileError(f"packaging.toml: {what} {snippet!r} {problem} in transcript.md")
    return hits[0]


def _toml_list(items: list[str]) -> str:
    return "[" + ", ".join(json.dumps(i, ensure_ascii=False) for i in items) + "]"


def write_packaging(p: Packaging, segments: list[Segment]) -> str:
    out = [
        f"title_options = {_toml_list(p.title_options)}",
        f"thumbnail_text = {_toml_list(p.thumbnail_text)}",
        f"description = {json.dumps(p.description, ensure_ascii=False)}",
        f"cold_open_from = {json.dumps(_anchor(segments, p.cold_open_start), ensure_ascii=False)}",
        f"cold_open_to = {json.dumps(_anchor(segments, p.cold_open_end), ensure_ascii=False)}",
    ]
    for c in p.clips:
        out += ["", "[[clips]]",
                f"title = {json.dumps(c.title, ensure_ascii=False)}",
                f"why = {json.dumps(c.why, ensure_ascii=False)}",
                f"from = {json.dumps(_anchor(segments, c.start_segment), ensure_ascii=False)}",
                f"to = {json.dumps(_anchor(segments, c.end_segment), ensure_ascii=False)}"]
    return "\n".join(out) + "\n"


def load_packaging(path: Path, segments: list[Segment]) -> Packaging | None:
    if not path.exists():
        return None
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return Packaging(
        title_options=data.get("title_options", []),
        thumbnail_text=data.get("thumbnail_text", []),
        description=data.get("description", ""),
        cold_open_start=_resolve(segments, data["cold_open_from"], "cold_open_from"),
        cold_open_end=_resolve(segments, data["cold_open_to"], "cold_open_to"),
        clips=[Clip(title=c["title"], why=c.get("why", ""),
                    start_segment=_resolve(segments, c["from"], f"clip {c['title']!r} from"),
                    end_segment=_resolve(segments, c["to"], f"clip {c['title']!r} to"))
               for c in data.get("clips", [])],
    )


# --- the last-question chain ---

QUESTIONS_FILE = Path(__file__).resolve().parent.parent / "show" / "next-guest-questions.md"


def pending_question(path: Path = QUESTIONS_FILE) -> tuple[str, str] | None:
    """The newest unanswered (asker, question) from the chain, if any."""
    if not path.exists():
        return None
    pending = None
    for line in path.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 4 and cells[0].isdigit() and "next guest" in cells[3]:
            pending = (cells[1], cells[2])
    return pending


# --- folders ---

def episode_folders(root: Path = EPISODES_DIR) -> list[Path]:
    return sorted(p for p in root.glob("[0-9][0-9][0-9]-*") if p.is_dir())


def next_number(root: Path = EPISODES_DIR) -> int:
    return max((int(p.name[:3]) for p in episode_folders(root)), default=0) + 1


def resolve_folder(ref: str, root: Path = EPISODES_DIR) -> Path:
    """Accept a path, a folder name, or an episode number like '2' or '002'."""
    path = Path(ref)
    if path.is_dir():
        return path
    if ref.isdigit():
        matches = [p for p in episode_folders(root) if int(p.name[:3]) == int(ref)]
        if matches:
            return matches[0]
    if (root / ref).is_dir():
        return root / ref
    raise EpisodeFileError(f"No episode folder {ref!r} in {root}")


def new_episode(figure: Figure, host: str, fmt_name: str = "longform", themes: str = "",
                slug: str = "", root: Path = EPISODES_DIR) -> Path:
    fmt = load_format(fmt_name)
    number = next_number(root)
    folder = root / f"{number:03d}-{slugify(slug or figure.slug.replace('_', '-'))}"
    folder.mkdir(parents=True)
    brief = Brief(number=number, figure=figure.slug, host=host, format=fmt_name, themes=themes)
    (folder / "brief.toml").write_text(write_brief(brief), encoding="utf-8")

    (folder / "research").mkdir()
    transcript = ["# Working title", "", "> One-line hook", ""]
    for i, c in enumerate(fmt.chapters, 1):
        beats = "\n".join(f"- {b}" for b in c.beats)
        (folder / "research" / f"{i:02d}-{c.id}.md").write_text(
            f"# {c.title}\n\nGoal: {c.goal}\nTarget: {c.minutes} min (~{c.minutes * WORDS_PER_MINUTE} words)\n\n"
            f"Beats:\n{beats}\n\n## Questions\n\n## Passages\n\n## Exact quotes\n\n## Gaps\n",
            encoding="utf-8")
        transcript += [f"## {c.title}", ""]
    (folder / "transcript.md").write_text("\n".join(transcript), encoding="utf-8")
    return folder


def load_episode(folder: Path) -> tuple[Episode, Brief]:
    brief = load_brief(folder)
    figure = load_figure(brief.figure)
    path = folder / "transcript.md"
    if not path.exists():
        raise EpisodeFileError(f"{folder} has no transcript.md")
    title, hook, chapters = parse_transcript(path.read_text(encoding="utf-8"), brief.host, figure.speaker_label)
    all_passages = {p.id: p for p in load_passages(figure)}
    cited = {c for ch in chapters for s in ch.segments for c in s.citations}
    episode = Episode(
        figure=figure, topic=brief.themes, title=title, hook=hook, chapters=chapters,
        passages={pid: all_passages[pid] for pid in sorted(cited) if pid in all_passages},
    )
    episode.packaging = load_packaging(folder / "packaging.toml", episode.segments)
    return episode, brief


def save_episode_files(ep: Episode, folder: Path, host: str) -> None:
    """Write the editable source files (used when a whole episode is generated at once)."""
    (folder / "transcript.md").write_text(write_transcript(ep, host), encoding="utf-8")
    if ep.packaging:
        (folder / "packaging.toml").write_text(write_packaging(ep.packaging, ep.segments), encoding="utf-8")


# --- checks ---

@dataclass
class CheckReport:
    errors: list[Issue]
    warnings: list[str]
    words: int
    target_words: int


def check_episode(ep: Episode, brief: Brief) -> CheckReport:
    """Every check that needs no model. Errors must be fixed before rendering; warnings are for review."""
    segments = ep.segments
    errors = mechanical_checks(segments, ep.passages)
    warnings = []

    host_lines = [s.text for s in segments if s.speaker == "HOST"]
    # While later chapters are still empty, the closing line isn't written yet: remind, don't block.
    complete = all(ch.segments for ch in ep.chapters)
    for where, line in (("opening", host_lines[:1]), ("closing", host_lines[-1:])):
        if not any("AI recreation" in text for text in line):
            if where == "closing" and not complete:
                warnings.append("The host's closing line must say the guest is an AI recreation "
                                "(required once the last chapter is written).")
                continue
            errors.append(Issue(segment=0, kind="disclosure", excerpt=where,
                                explanation=f"The host's {where} line must say the guest is an AI recreation.",
                                suggested_fix="Add the disclosure from show/bible.md."))

    fmt = load_format(brief.format) if brief.format else None
    target = fmt.minutes * WORDS_PER_MINUTE if fmt else 0
    words = sum(len(s.text.split()) for s in segments)
    if fmt and len(ep.chapters) != len(fmt.chapters):
        warnings.append(f"{len(ep.chapters)} chapters; the {fmt.name} format has {len(fmt.chapters)}.")
    if target and words < 0.75 * target:
        warnings.append(f"{words} words (~{words // WORDS_PER_MINUTE} min) is well under the "
                        f"{fmt.minutes}-minute target.")
    for i, s in enumerate(segments):
        if s.speaker == "GUEST" and not s.citations and len(s.text.split()) > LONG_UNCITED_WORDS:
            warnings.append(f"Segment {i}: long guest line with no citation: {s.text[:60]!r}")
    for ch in ep.chapters:
        if not ch.segments:
            warnings.append(f"Chapter {ch.title!r} is empty.")

    quotes: dict[str, int] = {}
    for i, s in enumerate(segments):
        for q in re.findall(r'"([^"]{20,})"', s.text):
            if q in quotes:
                warnings.append(f"Segment {i} repeats a quotation already used in segment {quotes[q]}: {q[:50]!r}")
            quotes.setdefault(q, i)
    return CheckReport(errors=errors, warnings=warnings, words=words, target_words=target)
